-- 1. Create database and schema
CREATE DATABASE IF NOT EXISTS DATAMIND_DB;
CREATE SCHEMA IF NOT EXISTS DATAMIND_DB.OWID;

-- 2. Create the target table for energy & climate indicators
CREATE OR REPLACE TABLE DATAMIND_DB.OWID.ENERGY_CONSUMPTION (
    COUNTRY VARCHAR(100),
    YEAR INT,
    PRIMARY_ENERGY_CONSUMPTION FLOAT,  -- TWh
    RENEWABLES_SHARE_ENERGY FLOAT,     -- %
    FOSSIL_SHARE_ENERGY FLOAT,         -- %
    CO2_EMISSIONS FLOAT,               -- Million metric tonnes
    POPULATION BIGINT,
    GDP FLOAT                          -- Constant 2015 USD
);

